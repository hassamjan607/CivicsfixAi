def seed_demo_complaints(engine) -> int:
    """
    Seed 30 realistic demo complaints into SQLite if none currently exist.
    Idempotent and safe to call. Returns number of complaints seeded.
    """
    with Session(engine) as session:
        # Check current count
        count = len(list(session.exec(select(Complaint))))
        if count >= 20:
            logger.info(f"Database already contains {count} complaints. Skipping demo seeding.")
            return count

        # Load departments mapping
        depts = {d.name: d.id for d in session.exec(select(Department))}
        default_dept_id = next(iter(depts.values()), 1)

        now = datetime.now(timezone.utc)
        seeded = 0

        for item in DEMO_COMPLAINTS:
            dept_id = depts.get(item["department_name"], default_dept_id)
            sla_hours = SLA_HOURS.get(item["department_name"], 48)
            created_at = now - timedelta(hours=item["hours_ago"])
            sla_deadline = created_at + timedelta(hours=sla_hours)

            # Check if tracking_id exists
            existing = session.exec(
                select(Complaint).where(Complaint.tracking_id == item["tracking_id"])
            ).first()

            if existing:
                continue

            complaint = Complaint(
                tracking_id=item["tracking_id"],
                category=item["category"],
                summary=item["summary"],
                description=item["description"],
                sentiment=item["sentiment"],
                vulnerable_group_flag=item["vulnerable_group_flag"],
                urgency_score=item["urgency_score"],
                urgency_reasons=json.dumps(item["urgency_reasons"]),
                status=item["status"],
                department_id=dept_id,
                latitude=item["latitude"],
                longitude=item["longitude"],
                address=item["address"],
                base_severity=item["base_severity"],
                photo_description=item.get("photo_description", "Photo captured by citizen mobile camera"),
                needs_human_review=item["needs_human_review"],
                suspected_fraud=False,
                anonymous=item.get("anonymous", False),
                escalated=item["escalated"],
                root_cause_flag=item["root_cause_flag"],
                recurrence_count=item["recurrence_count"],
                duplicate_count=0,
                sla_deadline=sla_deadline,
                created_at=created_at,
                updated_at=created_at,
            )
            session.add(complaint)
            session.flush()

            # Add status audit trail event
            initial_event = StatusEvent(
                complaint_id=complaint.id,
                old_status=ComplaintStatus.PENDING.value,
                new_status=complaint.status,
                actor_id="Citizen Submission",
                timestamp=created_at,
            )
            session.add(initial_event)

            if complaint.status == ComplaintStatus.RESOLVED.value:
                resolved_event = StatusEvent(
                    complaint_id=complaint.id,
                    old_status=ComplaintStatus.IN_PROGRESS.value,
                    new_status=ComplaintStatus.RESOLVED.value,
                    actor_id="Officer Inspector (ID #OF-42)",
                    timestamp=created_at + timedelta(hours=6),
                )
                session.add(resolved_event)

            seeded += 1

        session.commit()
        logger.info(f"Successfully seeded {seeded} demo complaints into database.")
        return seeded
